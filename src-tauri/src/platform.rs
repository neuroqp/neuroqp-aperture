//! The source filename never enters libvips' loader-option parser. Unix keeps
//! its existing symlinks; Windows uses a tiny path reference and Rust file I/O.
use std::fs;
use std::{
    io,
    path::{Path, PathBuf},
    process::Command,
};

pub fn source_alias(source: &Path, alias: &Path) -> io::Result<()> {
    #[cfg(unix)]
    {
        std::os::unix::fs::symlink(source, alias)
    }
    #[cfg(windows)]
    {
        fs::write(
            alias.with_extension("aperture-source.json"),
            serde_json::to_vec(source).map_err(io::Error::other)?,
        )?;
        fs::write(alias, [])
    }
}

pub fn source_path(alias: &Path) -> io::Result<PathBuf> {
    #[cfg(unix)]
    {
        Ok(alias.to_path_buf())
    }
    #[cfg(windows)]
    {
        // Only the job-local alias generated by the parent is a path reference.
        let reference = alias.with_extension("aperture-source.json");
        if reference.is_file() {
            serde_json::from_slice(&fs::read(reference)?).map_err(io::Error::other)
        } else {
            Ok(alias.to_path_buf())
        }
    }
}

pub fn command(program: &std::ffi::OsStr) -> Command {
    #[cfg(windows)]
    let command = {
        use std::os::windows::process::CommandExt;
        let mut command = Command::new(program);
        command.creation_flags(0x08000000); // CREATE_NO_WINDOW
        command
    };
    #[cfg(not(windows))]
    let command = Command::new(program);
    command
}

pub fn tool(program: &str) -> Command {
    if let Ok(executable) = std::env::current_exe() {
        #[cfg(windows)]
        let filename = format!("{program}.exe");
        #[cfg(not(windows))]
        let filename = program;
        let bundled = executable.with_file_name(filename);
        if bundled.is_file() {
            return command(bundled.as_os_str());
        }
    }
    command(std::ffi::OsStr::new(program))
}

pub fn open_image(input: &str) -> Result<libvips::VipsImage, String> {
    let (path, options) = input
        .rsplit_once('[')
        .filter(|_| input.ends_with(']'))
        .map_or((input, ""), |(p, o)| (p, o.strip_suffix(']').unwrap_or(o)));
    let path = source_path(Path::new(path)).map_err(|e| e.to_string())?;
    if path
        .extension()
        .is_some_and(|e| e.eq_ignore_ascii_case("bmp"))
    {
        // BMP is decoded in the isolated worker. Use one small Rust codec rather
        // than shipping ImageMagick (and its additional native dependencies).
        let reader = image::ImageReader::with_format(
            io::BufReader::new(fs::File::open(&path).map_err(|e| e.to_string())?),
            image::ImageFormat::Bmp,
        );
        let decoded = reader.decode().map_err(|e| e.to_string())?;
        let (width, height) = (decoded.width(), decoded.height());
        let (pixels, bands) = if decoded.color().has_alpha() {
            (decoded.into_rgba8().into_raw(), 4)
        } else {
            (decoded.into_rgb8().into_raw(), 3)
        };
        let width = i32::try_from(width).map_err(|_| "BMP width is too large")?;
        let height = i32::try_from(height).map_err(|_| "BMP height is too large")?;
        let image = libvips::VipsImage::new_from_memory_copy(
            &pixels,
            width,
            height,
            bands,
            libvips::ops::BandFormat::Uchar,
        )
        .map_err(|e| e.to_string())?;
        let image = libvips::ops::copy_with_opts(
            &image,
            &libvips::ops::CopyOptions {
                width,
                height,
                bands,
                format: libvips::ops::BandFormat::Uchar,
                coding: libvips::ops::Coding::None,
                interpretation: libvips::ops::Interpretation::Srgb,
                xres: 1.0,
                yres: 1.0,
                xoffset: 0,
                yoffset: 0,
            },
        )
        .map_err(|e| e.to_string())?;
        image
            .set_string("vips-loader", "bmp2vips")
            .map_err(|e| e.to_string())?;
        return Ok(image);
    }
    #[cfg(unix)]
    {
        let _ = options;
        libvips::VipsImage::new_from_file(input).map_err(|e| e.to_string())
    }
    #[cfg(windows)]
    {
        let file = fs::File::open(path).map_err(|e| e.to_string())?;
        libvips::VipsImage::new_from_file_handle(file, options).map_err(|e| e.to_string())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn source_alias_keeps_pixels_in_original_file() {
        let root = std::env::temp_dir().join(format!("aperture-source-{}", std::process::id()));
        fs::create_dir_all(&root).unwrap();
        let original = root.join("original [page=3] 日本語.tif");
        let alias = root.join("source.tif");
        fs::write(&original, b"pixels").unwrap();
        source_alias(&original, &alias).unwrap();
        assert_eq!(fs::read(source_path(&alias).unwrap()).unwrap(), b"pixels");
        fs::write(&original, b"updated").unwrap();
        assert_eq!(fs::read(source_path(&alias).unwrap()).unwrap(), b"updated");
        fs::remove_dir_all(root).unwrap();
    }
}
