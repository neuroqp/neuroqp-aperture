//! The source filename never enters libvips' loader-option parser. Unix keeps
//! its existing symlinks; Windows uses a tiny path reference and Rust file I/O.
use std::fs;
use std::{
    io,
    path::{Path, PathBuf},
    process::Command,
};

/// The file handle preserves identity across renames; ChangeTime also covers
/// writes/metadata changes when a caller restores LastWriteTime afterward.
#[cfg(windows)]
pub fn file_identity(file: &fs::File) -> Option<(u64, [u8; 16], i64)> {
    use std::{
        mem::{size_of, MaybeUninit},
        os::windows::io::AsRawHandle,
    };
    use windows_sys::Win32::Storage::FileSystem::{
        FileBasicInfo, FileIdInfo, GetFileInformationByHandleEx, FILE_BASIC_INFO, FILE_ID_INFO,
    };
    let mut identity = MaybeUninit::<FILE_ID_INFO>::uninit();
    let mut basic = MaybeUninit::<FILE_BASIC_INFO>::uninit();
    unsafe {
        if GetFileInformationByHandleEx(
            file.as_raw_handle(),
            FileIdInfo,
            identity.as_mut_ptr().cast(),
            size_of::<FILE_ID_INFO>() as u32,
        ) == 0
            || GetFileInformationByHandleEx(
                file.as_raw_handle(),
                FileBasicInfo,
                basic.as_mut_ptr().cast(),
                size_of::<FILE_BASIC_INFO>() as u32,
            ) == 0
        {
            return None;
        }
        let identity = identity.assume_init();
        let basic = basic.assume_init();
        (identity.FileId.Identifier != [0; 16] && basic.ChangeTime > 0).then_some((
            identity.VolumeSerialNumber,
            identity.FileId.Identifier,
            basic.ChangeTime,
        ))
    }
}

pub fn source_alias(source: &Path, alias: &Path) -> io::Result<()> {
    #[cfg(unix)]
    {
        std::os::unix::fs::symlink(source, alias)
    }
    #[cfg(windows)]
    {
        fs::write(
            alias.with_extension("aperture-source.json"),
            serde_json::to_vec(source).map_err(io::Error::other)?,
        )?;
        fs::write(alias, [])
    }
}

pub fn source_path(alias: &Path) -> io::Result<PathBuf> {
    #[cfg(unix)]
    {
        Ok(alias.to_path_buf())
    }
    #[cfg(windows)]
    {
        // Only the job-local alias generated by the parent is a path reference.
        let reference = alias.with_extension("aperture-source.json");
        if reference.is_file() {
            serde_json::from_slice(&fs::read(reference)?).map_err(io::Error::other)
        } else {
            Ok(alias.to_path_buf())
        }
    }
}

/// Resolve the same native cache directory used by Tauri before creating a WebView.
pub fn app_cache_root(identifier: &str) -> std::io::Result<PathBuf> {
    #[cfg(target_os = "linux")]
    let root = std::env::var_os("XDG_CACHE_HOME")
        .map(PathBuf::from)
        .filter(|path| path.is_absolute())
        .or_else(|| std::env::home_dir().map(|home| home.join(".cache")))
        .ok_or_else(|| std::io::Error::other("Cannot locate the user cache directory."))?;
    #[cfg(windows)]
    let root = windows_cache_root()?;
    Ok(root.join(identifier))
}

#[cfg(windows)]
fn windows_cache_root() -> std::io::Result<PathBuf> {
    use std::{
        ffi::{c_void, OsString},
        os::windows::ffi::OsStringExt,
    };
    use windows_sys::core::GUID;
    #[link(name = "shell32")]
    extern "system" {
        fn SHGetKnownFolderPath(
            folder: *const GUID,
            flags: u32,
            token: *mut c_void,
            path: *mut *mut u16,
        ) -> i32;
    }
    #[link(name = "ole32")]
    extern "system" {
        fn CoTaskMemFree(memory: *mut c_void);
    }
    const LOCAL_APP_DATA: GUID = GUID {
        data1: 0xf1b32785,
        data2: 0x6fba,
        data3: 0x4fcf,
        data4: [0x9d, 0x55, 0x7b, 0x8e, 0x7f, 0x15, 0x70, 0x91],
    };
    let mut directory = std::ptr::null_mut();
    // The OS returns an allocated, null-terminated UTF-16 directory path.
    unsafe {
        let result = SHGetKnownFolderPath(&LOCAL_APP_DATA, 0, std::ptr::null_mut(), &mut directory);
        if result < 0 || directory.is_null() {
            CoTaskMemFree(directory.cast());
            return Err(std::io::Error::other(format!(
                "Cannot locate LocalAppData: HRESULT {result:#x}"
            )));
        }
        let mut length = 0;
        while *directory.add(length) != 0 {
            length += 1;
        }
        let path = PathBuf::from(OsString::from_wide(std::slice::from_raw_parts(
            directory, length,
        )));
        CoTaskMemFree(directory.cast());
        Ok(path)
    }
}

pub fn command(program: &std::ffi::OsStr) -> Command {
    #[cfg(windows)]
    let command = {
        use std::os::windows::process::CommandExt;
        let mut command = Command::new(program);
        command.creation_flags(0x08000000); // CREATE_NO_WINDOW
        command
    };
    #[cfg(not(windows))]
    let command = Command::new(program);
    command
}

pub fn tool(program: &str) -> Command {
    if let Ok(executable) = std::env::current_exe() {
        #[cfg(windows)]
        let filename = format!("{program}.exe");
        #[cfg(not(windows))]
        let filename = program;
        let bundled = executable.with_file_name(filename);
        if bundled.is_file() {
            return command(bundled.as_os_str());
        }
    }
    command(std::ffi::OsStr::new(program))
}

pub fn open_image(input: &str) -> Result<libvips::VipsImage, String> {
    let (path, options) = input
        .rsplit_once('[')
        .filter(|_| input.ends_with(']'))
        .map_or((input, ""), |(p, o)| (p, o.strip_suffix(']').unwrap_or(o)));
    let path = source_path(Path::new(path)).map_err(|e| e.to_string())?;
    // Native .v files are scratch outputs created by Aperture, never selectable
    // source images. libvips requires a real filename to map this format.
    // The explicit loader takes the literal path, bypassing option parsing.
    if path.extension().is_some_and(|e| e == "v") {
        let path = fs::canonicalize(&path).map_err(|e| e.to_string())?;
        return libvips::ops::vipsload(path.to_str().ok_or("Scratch image path is not UTF-8")?)
            .map_err(|e| e.to_string());
    }
    if path
        .extension()
        .is_some_and(|e| e.eq_ignore_ascii_case("bmp"))
    {
        // BMP is decoded in the isolated worker. Use one small Rust codec rather
        // than shipping ImageMagick (and its additional native dependencies).
        let reader = image::ImageReader::with_format(
            io::BufReader::new(fs::File::open(&path).map_err(|e| e.to_string())?),
            image::ImageFormat::Bmp,
        );
        let decoded = reader.decode().map_err(|e| e.to_string())?;
        let (width, height) = (decoded.width(), decoded.height());
        let (pixels, bands) = if decoded.color().has_alpha() {
            (decoded.into_rgba8().into_raw(), 4)
        } else {
            (decoded.into_rgb8().into_raw(), 3)
        };
        let width = i32::try_from(width).map_err(|_| "BMP width is too large")?;
        let height = i32::try_from(height).map_err(|_| "BMP height is too large")?;
        let image = libvips::VipsImage::new_from_memory_copy(
            &pixels,
            width,
            height,
            bands,
            libvips::ops::BandFormat::Uchar,
        )
        .map_err(|e| e.to_string())?;
        let image = libvips::ops::copy_with_opts(
            &image,
            &libvips::ops::CopyOptions {
                width,
                height,
                bands,
                format: libvips::ops::BandFormat::Uchar,
                coding: libvips::ops::Coding::None,
                interpretation: libvips::ops::Interpretation::Srgb,
                xres: 1.0,
                yres: 1.0,
                xoffset: 0,
                yoffset: 0,
            },
        )
        .map_err(|e| e.to_string())?;
        image
            .set_string("vips-loader", "bmp2vips")
            .map_err(|e| e.to_string())?;
        return Ok(image);
    }
    #[cfg(unix)]
    {
        let _ = options;
        libvips::VipsImage::new_from_file(input).map_err(|e| e.to_string())
    }
    #[cfg(windows)]
    {
        let file = fs::File::open(path).map_err(|e| e.to_string())?;
        libvips::VipsImage::new_from_file_handle(file, options).map_err(|e| e.to_string())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn source_alias_keeps_pixels_in_original_file() {
        let root = std::env::temp_dir().join(format!("aperture-source-{}", std::process::id()));
        fs::create_dir_all(&root).unwrap();
        let original = root.join("original [page=3] 日本語.tif");
        let alias = root.join("source.tif");
        fs::write(&original, b"pixels").unwrap();
        source_alias(&original, &alias).unwrap();
        assert_eq!(fs::read(source_path(&alias).unwrap()).unwrap(), b"pixels");
        fs::write(&original, b"updated").unwrap();
        assert_eq!(fs::read(source_path(&alias).unwrap()).unwrap(), b"updated");
        fs::remove_dir_all(root).unwrap();
    }
    #[cfg(windows)]
    #[test]
    fn windows_identity_changes_with_restored_mtime_and_file_replacement() {
        let root = std::env::temp_dir().join(format!(
            "aperture-file-identity-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        fs::create_dir(&root).unwrap();
        let path = root.join("source [pixels] 日本語.tif");
        fs::write(&path, b"AAAA").unwrap();
        let metadata = fs::metadata(&path).unwrap();
        let modified = metadata.modified().unwrap();
        let identity = || {
            file_identity(&fs::File::open(&path).unwrap())
                .expect("NTFS identity and change time must be available on the Windows runner")
        };
        let original = identity();
        std::thread::sleep(std::time::Duration::from_millis(20));
        fs::write(&path, b"BBBB").unwrap();
        fs::OpenOptions::new()
            .write(true)
            .open(&path)
            .unwrap()
            .set_times(fs::FileTimes::new().set_modified(modified))
            .unwrap();
        assert_eq!(fs::metadata(&path).unwrap().len(), metadata.len());
        assert_eq!(fs::metadata(&path).unwrap().modified().unwrap(), modified);
        let edited = identity();
        assert_eq!(original.0, edited.0);
        assert_eq!(original.1, edited.1);
        assert_ne!(
            original.2, edited.2,
            "Restoring mtime must not hide the change time"
        );
        let replacement = root.join("replacement.tif");
        fs::write(&replacement, b"CCCC").unwrap();
        fs::OpenOptions::new()
            .write(true)
            .open(&replacement)
            .unwrap()
            .set_times(fs::FileTimes::new().set_modified(modified))
            .unwrap();
        fs::rename(replacement, &path).unwrap();
        assert_eq!(fs::metadata(&path).unwrap().modified().unwrap(), modified);
        assert_ne!(
            edited.1,
            identity().1,
            "Replacing the file must change its file ID"
        );
        fs::remove_dir_all(root).unwrap();
    }
}
